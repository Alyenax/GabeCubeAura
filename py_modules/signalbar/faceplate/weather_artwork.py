from dataclasses import dataclass
from datetime import datetime
from functools import lru_cache
import hashlib
import json
from pathlib import Path
import zlib

from signalbar.faceplate.gif import encode as encode_indexed_gif
from signalbar.faceplate.gif import quantize
from signalbar.faceplate.playtime import overlay_timer
from signalbar.faceplate.artwork_dashboard import (
    REVISION as ARTWORK_DASHBOARD_REVISION,
    build_artwork_dashboard, _draw_weather_notch, _weather_icon,
    _notch_temperature, NOTCH_ICON_ORIGIN,
)
from signalbar.faceplate.scenes import (
    BLACK, HEIGHT, PHASE_PALETTES, PIXELS, WEATHER_VARIANTS, WIDTH, Canvas, SceneResult,
    build_weather_scene, display_temperature, draw_status_rail, draw_text,
    draw_text_centered, measure_text, select_dashboard_context, solar_phase,
    validate_variant,
)


WEATHER_ARTWORK_THEME = "weather-artwork-v1"
WEATHER_ARTWORK_V2_THEME = "weather-artwork-v2"
WEATHER_ARTWORK_THEMES = (WEATHER_ARTWORK_THEME, WEATHER_ARTWORK_V2_THEME)
WEATHER_ARTWORK_REVISION = "weather-artwork-v1-runtime-3"
WEATHER_ARTWORK_V2_REVISION = "weather-artwork-v2-runtime-4"
WEATHER_ARTWORK_OUTPUT_REVISION = "weather-artwork-v1-output-4"
WEATHER_ARTWORK_V2_OUTPUT_REVISION = "weather-artwork-v2-output-8"
WEATHER_ARTWORK_DASHBOARD_REVISION = "weather-artwork-v1-dashboard-10"
WEATHER_ARTWORK_V2_DASHBOARD_REVISION = "weather-artwork-v2-dashboard-14"
RAIN_PHASE_REVISION = "weather-rain-phases-1"
WINTER_PHASE_REVISION = "weather-winter-phases-2"
RUNTIME_ROOT = Path(__file__).resolve().parents[3] / "assets/faceplate/weather-artwork-v1"
V2_RUNTIME_ROOT = Path(__file__).resolve().parents[3] / "assets/faceplate/weather-artwork-v2"
CATALOG_PATH = RUNTIME_ROOT / "catalog.json"


@dataclass(frozen=True)
class WeatherArtworkSelection:
    preset_id: str = ""
    selection_status: str = "fallback"
    reason: str = "uncovered"


@dataclass(frozen=True)
class WeatherArtworkResult(SceneResult):
    """Scene result retaining the collection's intended shared palette."""

    def gif(self) -> bytes:
        # V2 source GIFs and the catalogue showcase are authored with a shared
        # 256-colour palette.  Keeping that precision in the hardware renderer
        # preserves the deliberately subtle lunar/cloud breathing instead of
        # making the installed result look flatter than Pixel Studio.  V1
        # retains its established 128-colour contract.
        colours = 256 if self.revision in {
            WEATHER_ARTWORK_V2_REVISION,
            WEATHER_ARTWORK_V2_DASHBOARD_REVISION,
        } else 128
        palette, indexed = quantize(b"".join(self.frames), colours=colours)
        frame_size = PIXELS
        indexed_frames = tuple(
            indexed[offset:offset + frame_size]
            for offset in range(0, len(indexed), frame_size)
        )
        payload = encode_indexed_gif(
            WIDTH, HEIGHT, palette, indexed_frames,
            self.delays_cs or self.delay_cs, loop=True,
        )
        if len(payload) > 512 * 1024:
            raise ValueError("Weather Artwork GIF exceeds the software safety limit")
        return payload


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _theme_contract(visual_theme: str):
    visual_theme = str(visual_theme)
    contracts = {
        WEATHER_ARTWORK_THEME: (
            RUNTIME_ROOT, WEATHER_ARTWORK_REVISION,
            WEATHER_ARTWORK_DASHBOARD_REVISION,
        ),
        WEATHER_ARTWORK_V2_THEME: (
            V2_RUNTIME_ROOT, WEATHER_ARTWORK_V2_REVISION,
            WEATHER_ARTWORK_V2_DASHBOARD_REVISION,
        ),
    }
    if visual_theme not in contracts:
        raise ValueError("unknown Weather Artwork theme")
    return contracts[visual_theme]


def weather_artwork_cache_revision(visual_theme: str, kind: str = "weather", condition=None) -> str:
    """Return the asset identity that must participate in persistent caches.

    Dashboard snapshots depend on both the selected background collection and
    their own layout revision.  Exposing this small public contract keeps the
    backend from serving a GIF generated by an older installed Lab after the
    precompiled RGB packs have changed.
    """
    _runtime_root, collection_revision, dashboard_revision = _theme_contract(
        visual_theme,
    )
    # Only day cloud-break renders changed; keep every other cache identity.
    suffix = ":breaks-day-source-exposure-1" if (
        str(visual_theme) == WEATHER_ARTWORK_V2_THEME and condition == "breaks"
    ) else ""
    if str(kind) == "dashboard":
        return f"{collection_revision}:{dashboard_revision}:{ARTWORK_DASHBOARD_REVISION}{suffix}"
    output_revision = (
        WEATHER_ARTWORK_V2_OUTPUT_REVISION
        if str(visual_theme) == WEATHER_ARTWORK_V2_THEME
        else WEATHER_ARTWORK_OUTPUT_REVISION
    )
    return f"{collection_revision}:{output_revision}{suffix}"


@lru_cache(maxsize=2)
def load_catalog(visual_theme=WEATHER_ARTWORK_THEME) -> dict:
    runtime_root, revision, _dashboard_revision = _theme_contract(visual_theme)
    payload = json.loads((runtime_root / "catalog.json").read_text(encoding="utf-8"))
    if payload.get("schema") != 1 or payload.get("theme") != visual_theme:
        raise ValueError("invalid Weather Artwork catalog")
    if payload.get("collection_revision") != revision:
        raise ValueError("unsupported Weather Artwork collection revision")
    if (payload.get("width"), payload.get("height")) != (WIDTH, HEIGHT):
        raise ValueError("Weather Artwork catalog has invalid dimensions")
    if int(payload.get("frame_count", 0)) != 24:
        raise ValueError("Weather Artwork catalog has invalid frame count")
    presets = payload.get("presets")
    expected_ids = {
        f"{condition}:{variant}"
        for condition, names in WEATHER_VARIANTS.items()
        for variant in range(len(names))
    }
    if not isinstance(presets, list) or len(presets) != len(expected_ids):
        raise ValueError("Weather Artwork catalog must contain all 22 variants")
    ids = {str(item.get("id", "")) for item in presets if isinstance(item, dict)}
    if ids != expected_ids:
        raise ValueError("Weather Artwork preset ids must match GabeCubeAura variants")
    return payload


@lru_cache(maxsize=1)
def _rain_phase_catalog():
    payload = json.loads((V2_RUNTIME_ROOT / "rain-phases.json").read_text(encoding="utf-8"))
    entries = payload.get("entries", [])
    if (payload.get("schema") != 1 or payload.get("revision") != RAIN_PHASE_REVISION
            or payload.get("frame_count") != 24 or payload.get("frame_duration_cs") != 10
            or len(entries) != 4
            or {(row.get("id"), row.get("phase")) for row in entries}
            != {(f"rain:{variant}", phase) for variant in (0, 1) for phase in ("day", "night")}):
        raise ValueError("invalid Weather rain day/night catalog")
    return {(row["id"], row["phase"]): row for row in entries}


@lru_cache(maxsize=1)
def _winter_phase_catalog():
    payload = json.loads((V2_RUNTIME_ROOT / "winter-phases.json").read_text(encoding="utf-8"))
    entries = payload.get('entries', [])
    expected = {(f'{condition}:{variant}', phase) for condition in ('snow', 'storm')
                for variant in (0, 1) for phase in ('day', 'night')}
    if (payload.get('schema') != 1 or payload.get('revision') != WINTER_PHASE_REVISION
            or payload.get('frame_count') != 24 or payload.get('frame_duration_cs') != 10
            or len(entries) != 8 or {(row.get('id'), row.get('phase')) for row in entries} != expected):
        raise ValueError('invalid Weather snow/storm day/night catalog')
    return {(row['id'], row['phase']): row for row in entries}


def _preset(preset_id: str, visual_theme=WEATHER_ARTWORK_THEME, phase=None) -> dict:
    for item in load_catalog(visual_theme)["presets"]:
        if item["id"] == preset_id:
            if visual_theme == WEATHER_ARTWORK_V2_THEME and preset_id in {"rain:0", "rain:1"} and phase:
                day_night = "day" if phase in {"dawn", "day"} else "night"
                return {**item, **_rain_phase_catalog()[(preset_id, day_night)]}
            if visual_theme == WEATHER_ARTWORK_V2_THEME and preset_id in {'snow:0', 'snow:1', 'storm:0', 'storm:1'} and phase:
                day_night = 'day' if phase in {'dawn', 'day'} else 'night'
                return {**item, **_winter_phase_catalog()[(preset_id, day_night)]}
            return item
    raise ValueError("unknown Weather Artwork preset")


@lru_cache(maxsize=6)
def _backgrounds(visual_theme: str, preset_id: str, phase=None) -> tuple[bytes, ...]:
    runtime_root, _revision, _dashboard_revision = _theme_contract(visual_theme)
    item = _preset(preset_id, visual_theme, phase)
    filename = str(item["background_pack"])
    path = (runtime_root / filename).resolve()
    if path.parent != runtime_root.resolve() or path.suffix != ".rgbz":
        raise ValueError("unsafe Weather Artwork background path")
    packed = path.read_bytes()
    if _sha256(packed) != item["background_pack_sha256"]:
        raise ValueError("Weather Artwork background hash mismatch")
    raw = zlib.decompress(packed)
    if _sha256(raw) != item["background_raw_sha256"]:
        raise ValueError("Weather Artwork decoded background hash mismatch")
    frame_size = PIXELS * 3
    expected = int(item["frame_count"]) * frame_size
    if len(raw) != expected:
        raise ValueError("Weather Artwork background has invalid decoded size")
    return tuple(raw[offset:offset + frame_size] for offset in range(0, len(raw), frame_size))


def select_weather_artwork(condition, variant, phase, *, weather_code=None,
                           wind_speed_kmh=None,
                           visual_theme=WEATHER_ARTWORK_THEME) -> WeatherArtworkSelection:
    """Map one GabeCubeAura condition and variant to its exact Artwork preset."""
    condition = str(condition)
    variant = int(variant)
    validate_variant(condition, variant)
    phase = str(phase)
    if phase not in PHASE_PALETTES:
        raise ValueError("unknown solar phase")
    # These inputs stay accepted for request-schema compatibility. The complete
    # V2 collection deliberately follows the user's selected variant exactly;
    # fog and wind remain preserved supplementary concepts, not silent overrides.
    del weather_code, wind_speed_kmh
    preset_id = f"{condition}:{variant}"
    try:
        _preset(preset_id, visual_theme)
    except ValueError:
        return WeatherArtworkSelection(reason="future-variant-uncovered")
    return WeatherArtworkSelection(preset_id, "exact", "condition-variant-exact")


def _canvas_from_rgb(frame: bytes) -> Canvas:
    if len(frame) != PIXELS * 3:
        raise ValueError("Weather Artwork frame must be RGB 64 x 54")
    canvas = Canvas(BLACK)
    canvas.pixels = [tuple(frame[index:index + 3]) for index in range(0, len(frame), 3)]
    return canvas


def _add_weather_badge(frame: bytes, condition: str, temperature: int, suffix: str) -> bytes:
    canvas = _canvas_from_rgb(frame)
    # Weather and both Dashboard routes share the exact 27-column notch.
    # The seven released columns come directly from the badge-free pack.
    _draw_weather_notch(canvas)
    _weather_icon(canvas, condition, *NOTCH_ICON_ORIGIN)
    _notch_temperature(canvas, None, "celsius", label=f"{temperature}°{suffix}")
    return canvas.bytes()


def _frame_load(frame: bytes) -> float:
    return sum(frame) / (len(frame) * 255.0)


def _dashboard_datetime(value, name: str) -> datetime:
    if isinstance(value, datetime):
        return value
    try:
        return datetime.fromisoformat(str(value))
    except ValueError as error:
        raise ValueError(f"invalid {name}") from error


def build_weather_artwork_dashboard_snapshot(
    instant, condition, variant, temperature_c, unit, sunrise, sunset, city="",
    precipitation_probability=None, context=None, clock_24h=True,
    status=None, battery=None, visual_theme=WEATHER_ARTWORK_THEME,
    bottom_mode="next_hour", controllers=(), battery_style="percent",
    show_p2=False, forecast=None, show_weather_notch=True,
    ux_enabled=False, clock_position="left", game_running=False,
    show_game_session=False, session_minutes=0, connected_controller_count=None,
    countdown=None, show_clock=False, show_status_rail=True,
    game_row="existing", game_stats=None, weather_position="right",
):
    """Build an animated Home dashboard over the exact Weather artwork loop.

    Every background frame receives the same minute, weather notch and strict
    bottom row. The systemic Weather loop can therefore repeat freely without
    making the clock move backwards; the next ACK-paced upload replaces the
    complete loop when the displayed minute changes.
    """
    instant = _dashboard_datetime(instant, "instant").replace(second=0, microsecond=0)
    sunrise = _dashboard_datetime(sunrise, "sunrise")
    sunset = _dashboard_datetime(sunset, "sunset")
    validate_variant(str(condition), int(variant))
    phase = solar_phase(instant, sunrise, sunset)
    if str(condition) in {"rain", "snow", "storm"} and visual_theme == WEATHER_ARTWORK_V2_THEME:
        phase = "day" if sunrise <= instant < sunset else "night"
    runtime_root, revision, dashboard_revision = _theme_contract(visual_theme)
    del runtime_root
    selection = select_weather_artwork(
        condition, int(variant), phase, visual_theme=visual_theme,
    )
    if not selection.preset_id:
        raise ValueError("Weather Artwork dashboard variant is unavailable")
    item = _preset(selection.preset_id, visual_theme, phase)

    # Use the exact same strict header and bottom rail as an artwork-backed
    # Dashboard. The selected systemic Weather scene simply becomes its
    # background; there is only one Dashboard grammar to learn.
    backgrounds = _backgrounds(visual_theme, selection.preset_id, phase)
    dashboard = build_artwork_dashboard(
        backgrounds, instant, session_minutes, battery,
        treatment="cinema", show_clock=bool(show_clock), show_status_rail=bool(show_status_rail),
        show_session=False, show_battery=True,
        background_signature=item["background_raw_sha256"],
        source_frame_count=len(backgrounds), status=status,
        weather={"condition": condition, "temperature_c": temperature_c},
        bottom_mode=bottom_mode, controllers=controllers,
        battery_style=battery_style, show_p2=show_p2,
        forecast=forecast, unit=unit,
        show_weather_notch=show_weather_notch,
        ux_enabled=ux_enabled,
        clock_24h=clock_24h,
        clock_position=clock_position, game_running=game_running,
        show_game_session=show_game_session,
        connected_controller_count=connected_controller_count,
        countdown=countdown, game_row=game_row, game_stats=game_stats,
        weather_position=weather_position,
    )
    temperature, suffix = display_temperature(temperature_c, unit)
    frames, power_scale = dashboard.frames, 1.0
    identity = {
        "background": item["background_raw_sha256"],
        "collection_revision": revision,
        "clock_24h": bool(clock_24h) if show_clock else None,
        "condition": str(condition),
        "instant": instant.isoformat() if show_clock else None,
        "dashboard_signature": dashboard.signature,
        "bottom_mode": bottom_mode,
        "show_weather_notch": bool(show_weather_notch),
        "revision": dashboard_revision,
        "visual_theme": visual_theme,
        "temperature": temperature if show_weather_notch else None,
        "unit": suffix,
        "variant": int(variant),
    }
    signature = hashlib.sha256(json.dumps(
        identity, sort_keys=True, separators=(",", ":"),
    ).encode("utf-8")).hexdigest()
    result = WeatherArtworkResult(
        frames, dashboard.delay_cs, signature, str(condition), int(variant), phase,
        temperature, suffix, str(city or "").strip(), (),
        dashboard_revision,
    )
    return result, {
        "preset_id": selection.preset_id,
        "selection_status": selection.selection_status,
        "selection_reason": selection.reason,
        "variant_name": item.get("variant_name", item.get("label", "")),
        "source_scene": item.get("source_scene", ""),
        "collection_revision": revision,
        "dashboard_revision": dashboard_revision,
        "visual_theme": visual_theme,
        "peak_load": round(max(map(_frame_load, frames)), 6),
        "power_scale": round(power_scale, 6),
    }


def build_weather_artwork_scene(condition, variant, temperature_c, unit, phase,
                                city="", *, weather_code=None, wind_speed_kmh=None,
                                visual_theme=WEATHER_ARTWORK_THEME, countdown=None):
    """Return ``(SceneResult, metadata)`` for Artwork V1 or its honest fallback."""
    validate_variant(condition, int(variant))
    if phase not in PHASE_PALETTES:
        raise ValueError("unknown solar phase")
    _runtime_root, revision, _dashboard_revision = _theme_contract(visual_theme)
    selection = select_weather_artwork(
        condition, int(variant), phase,
        weather_code=weather_code, wind_speed_kmh=wind_speed_kmh,
        visual_theme=visual_theme,
    )
    if not selection.preset_id:
        result = build_weather_scene(
            condition, int(variant), temperature_c, unit, phase, city=city,
        )
        return result, {
            "preset_id": "",
            "selection_status": "fallback",
            "selection_reason": selection.reason,
            "fallback_renderer": "integrated",
            "collection_revision": revision,
            "visual_theme": visual_theme,
            "peak_load": round(max(map(_frame_load, result.frames)), 6),
        }

    item = _preset(selection.preset_id, visual_theme, phase)
    temperature, suffix = display_temperature(temperature_c, unit)
    frames = tuple(
        overlay_timer(_add_weather_badge(frame, str(condition), temperature, suffix), countdown)
        for frame in _backgrounds(visual_theme, selection.preset_id, phase)
    )
    power_scale = 1.0
    signature_payload = {
        "background": item["background_raw_sha256"],
        "condition": str(condition),
        "preset_id": selection.preset_id,
        "revision": revision,
        "visual_theme": visual_theme,
        "output_revision": WEATHER_ARTWORK_V2_OUTPUT_REVISION
            if visual_theme == WEATHER_ARTWORK_V2_THEME else WEATHER_ARTWORK_OUTPUT_REVISION,
        "countdown": countdown,
        "temperature": temperature,
        "unit": suffix,
        "variant": int(variant),
    }
    signature = hashlib.sha256(json.dumps(
        signature_payload, sort_keys=True, separators=(",", ":"),
    ).encode("utf-8")).hexdigest()
    delay = int(item["frame_duration_cs"])
    result = WeatherArtworkResult(
        frames, delay, signature, str(condition), int(variant), str(phase),
        temperature, suffix, str(city or "").strip(), (delay,) * len(frames),
        revision,
    )
    return result, {
        "preset_id": selection.preset_id,
        "selection_status": selection.selection_status,
        "selection_reason": selection.reason,
        "variant_name": item.get("variant_name", item.get("label", "")),
        "source_scene": item.get("source_scene", ""),
        "fallback_renderer": "",
        "collection_revision": revision,
        "visual_theme": visual_theme,
        "peak_load": round(max(map(_frame_load, frames)), 6),
        "power_scale": round(power_scale, 6),
    }
