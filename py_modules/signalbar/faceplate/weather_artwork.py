"""Weather-only Artwork V1 renderer for the 64 x 54 JSAUX faceplate.

The runtime bundle contains compressed RGB backgrounds prepared ahead of time.
This module is stdlib-only: it never opens source artwork, decodes a GIF, or
performs network work while a Weather scene is requested.
"""

